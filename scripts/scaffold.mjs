// Typefolio scaffold — zero-dependency CLI that writes a fresh site.config.ts.
// Run: npm run scaffold
import { createInterface } from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const isTTY = Boolean(input.isTTY);

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG_PATH = join(root, 'site.config.ts');

const PRESETS = [
  { id: 'paper', label: 'Paper — warm light theme (default)' },
  { id: 'ink', label: 'Ink — inverted dark theme' },
  { id: 'forest', label: 'Forest — deep green + bone' },
  { id: 'clay', label: 'Clay — warm paper + terracotta' },
];

const rl = isTTY ? createInterface({ input, output }) : null;

/**
 * Read one answer. In a real terminal this is interactive; when stdin is
 * piped (or not a TTY), answers are consumed line-by-line from the pipe so
 * `printf '...\n' | npm run scaffold` also works.
 */
let pipedLines = [];
let pipedIndex = 0;
if (!isTTY) {
  try {
    pipedLines = readFileSync(0, 'utf8').split(/\r?\n/);
  } catch {
    pipedLines = [];
  }
}

async function ask(question, def = '') {
  const prompt = `${question}${def ? ` [${def}]` : ''}: `;
  if (!isTTY) {
    const answer = (pipedLines[pipedIndex++] ?? '').trim();
    output.write(`${prompt}${answer}\n`);
    return answer || def;
  }
  const answer = (await rl.question(prompt)).trim();
  return answer || def;
}

/** Make free text safe to embed in a TS template literal. */
function clean(value) {
  return value.replace(/\\/g, '\\\\').replace(/`/g, "'").replace(/\$\{/g, '{');
}

function toStringArray(value) {
  return value
    .split(',')
    .map((part) => clean(part.trim()))
    .filter(Boolean);
}

