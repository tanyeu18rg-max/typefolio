async function main() {
  console.log('\n  Typefolio scaffold — answer a few prompts, get a fresh site.config.ts.\n');

  if (existsSync(CONFIG_PATH)) {
    const overwrite = (await ask('site.config.ts already exists. Overwrite?', 'y')).toLowerCase();
    if (overwrite !== 'y' && overwrite !== 'yes') {
      console.log('Aborted — existing site.config.ts kept.');
      if (rl) rl.close();
      return;
    }
  }

  const name = clean(await ask('Your name', 'Alex Carter'));
  const roles = toStringArray(
    await ask('Roles (comma-separated)', 'Product Designer, Creative Developer'),
  );
  const location = clean(await ask('Location', 'Portland, Oregon'));
  const availability = clean(await ask('Availability note', 'Available for new projects'));
  const email = clean(await ask('Contact email', 'hello@example.com'));
  const eyebrow = clean(await ask('Hero eyebrow', 'Independent designer & developer'));
  const heroLines = toStringArray(
    await ask('Hero headline lines (comma-separated)', 'Design, & Code'),
  );
  const identityLines = toStringArray(
    await ask('Identity stack lines (comma-separated)', `${name}, Designs, Interfaces, & Systems`),
  );
  const intro = clean(
    await ask(
      'Intro sentence',
      'I design and build websites, products, and interfaces — pairing strong typography with thoughtful engineering.',
    ),
  );
  const manifestoLines = toStringArray(
    await ask('Manifesto lines (comma-separated)', 'Good work, speaks quietly.'),
  );

  console.log('\nToken presets:');
  PRESETS.forEach((p, i) => console.log(`  ${i + 1}. ${p.label}`));
  const choice = await ask('Pick a preset (1-4)', '1');
  const preset = PRESETS[Number.parseInt(choice, 10) - 1] ?? PRESETS[0];

  const answers = {
    name,
    roles: roles.length > 0 ? roles : ['Designer'],
    location,
    availability,
    email,
    eyebrow,
    heroLines: heroLines.length > 0 ? heroLines : ['Hello'],
    identityLines: identityLines.length > 0 ? identityLines : [name],
    intro,
    manifestoLines: manifestoLines.length > 0 ? manifestoLines : ['Make good work.'],
    preset: preset.id,
  };

  writeFileSync(CONFIG_PATH, renderConfig(answers));
  if (rl) rl.close();

  console.log(`\n  Wrote site.config.ts with the "${preset.id}" preset.`);
  console.log(
    '  Next: npm run dev — then replace the placeholder work images in public/assets/.\n',
  );
}

main().catch((error) => {
  console.error(error);
  if (rl) rl.close();
  process.exit(1);
});
